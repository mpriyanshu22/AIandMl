"""
app/models/schemas.py
Pydantic schemas defining request and response contracts for our API.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

# ==========================================
# 1. Health & Status Schemas
# ==========================================

class HealthResponse(BaseModel):
    """Response schema for GET /health endpoint."""
    status: str = Field(..., example="ok", description="Status of the API service")
    app_name: str = Field(..., example="FastAPI RAG Knowledge Base", description="Name of the running application")
    version: str = Field(..., example="1.0.0", description="Application semantic version")


# ==========================================
# 2. Document Ingestion Schemas
# ==========================================

class DocumentIngestRequest(BaseModel):
    """
    Request schema for POST /documents/ingest.
    Defines what information the user must provide to add knowledge.
    """
    title: str = Field(..., min_length=1, max_length=200, example="FastAPI Intro", description="Title of the document")
    content: str = Field(..., min_length=10, example="FastAPI is a modern web framework for Python...", description="Full raw text content of the document")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, example={"author": "Dev", "category": "tech"}, description="Optional metadata tags")


class DocumentIngestResponse(BaseModel):
    """
    Response schema for POST /documents/ingest.
    Informs the user how the document was ingested and chunked.
    """
    document_id: str = Field(..., description="Unique identifier generated for this document")
    title: str = Field(..., description="Title of the stored document")
    chunks_created: int = Field(..., example=3, description="Number of text chunks created and embedded")
    message: str = Field(..., example="Document ingested successfully")


# ==========================================
# 3. RAG Query & Search Schemas
# ==========================================

class QueryRequest(BaseModel):
    """
    Request schema for POST /query.
    What the user sends when asking a question against the knowledge base.
    """
    query: str = Field(..., min_length=2, example="What is FastAPI?", description="The question you want to ask")
    top_k: Optional[int] = Field(default=3, ge=1, le=10, description="Number of context chunks to retrieve (between 1 and 10)")


class SourceChunk(BaseModel):
    """
    Schema representing an individual retrieved piece of context.
    Provides transparency and provenance (citations).
    """
    chunk_id: str = Field(..., description="ID of the chunk in ChromaDB")
    document_title: str = Field(..., description="Title of the source document")
    text: str = Field(..., description="The excerpt/snippet of text that was retrieved")
    score: Optional[float] = Field(None, description="Similarity score or distance metric")


class QueryResponse(BaseModel):
    """
    Response schema for POST /query.
    Contains both the AI-generated answer and the exact context chunks used.
    """
    query: str = Field(..., description="The original question asked")
    answer: str = Field(..., description="The synthesized answer generated by RAG")
    sources: List[SourceChunk] = Field(default_factory=list, description="List of source chunks used to generate the answer")